// Project-wide setup (`[project]` in the manifest): files ADE generates in
// <root>/<project>/, which is not a git tree. repoDirs only counts directories
// holding a .bare as repos, so none of these is ever "not in manifest anymore".

const (
	// AgentsFile is the project's generated agent guidance in the project directory.
	AgentsFile = "AGENTS.md"
	// agentsMarker starts the one-line header of the generated AGENTS.md; ADE
	// only rewrites or removes a file that carries it.
	agentsMarker = "<!-- Generated by ADE"
)

// SetupResult is what the project-wide setup of one project did to its generated files.
type SetupResult struct {
	Project string `json:"project"`
	// Written and Removed are generated files, relative to the project directory.
	Written  []string `json:"written,omitempty"`
	Removed  []string `json:"removed,omitempty"`
	Warnings []string `json:"warnings,omitempty"`
}

// ReadAgents returns the project's AGENTS.md without ADE's generated header, or
// "" when there is none. Skills and agent prompts carry it next to the repo's own.
func ReadAgents(projectDir string) string {
	b, err := os.ReadFile(filepath.Join(projectDir, AgentsFile))
	if err != nil {
		return ""
	}
	text := string(b)
	if first, rest, ok := strings.Cut(text, "\n"); ok && strings.HasPrefix(first, agentsMarker) {
		text = rest
	}
	return strings.TrimSpace(text)
}

// syncSetup generates the project-wide files of one run.
func (s *Service) syncSetup(ctx context.Context, r *run) SetupResult {
	res := SetupResult{Project: r.name}
	if !r.stale { // the agents file comes from the manifest's source, which failed
		s.syncAgents(r, &res)
	}
	s.syncShell(r, &res)
	s.syncGroups(ctx, r, &res)
	return res
}

// --- AGENTS.md --------------------------------------------------------------

func (s *Service) syncAgents(r *run, res *SetupResult) {
	rel := r.manifest.Project.Agents
	dst := filepath.Join(r.dir, AgentsFile)
	if rel == "" {
		s.removeGenerated(dst, AgentsFile, agentsMarker, res)
		return
	}
	src, display, strict, err := s.agentsSource(r)
	if err != nil {
		res.Warnings = append(res.Warnings, "project.agents: "+err.Error())
		return
	}
	body, err := readSourceFile(src, strict)
	if err != nil {
		res.Warnings = append(res.Warnings, fmt.Sprintf("project.agents: %s: %v", display, err))
		return
	}
	header := fmt.Sprintf("%s from project.agents of the manifest; edit %s, not this file. -->\n\n", agentsMarker, display)
	s.writeGenerated(dst, AgentsFile, agentsMarker, []byte(header+strings.TrimSpace(string(body))+"\n"), 0o644, res)
}

// agentsSource resolves project.agents to a file on this machine. display is
// where a person edits it; strict forbids following a symlink (the file sits
// in a cloned repository).
func (s *Service) agentsSource(r *run) (path, display string, strict bool, err error) {
	rel := filepath.FromSlash(r.manifest.Project.Agents)
	switch {
	case strings.HasPrefix(r.source, "git+"):
		repoURL, file, err := splitGitSpec(strings.TrimPrefix(r.source, "git+"))
		if err != nil {
			return "", "", false, err
		}
		inRepo := filepath.ToSlash(filepath.Join(filepath.Dir(filepath.FromSlash(file)), rel))
		clone := s.manifestCacheDir(repoURL)
		real, err := resolveWithin(clone, filepath.Join(clone, filepath.FromSlash(inRepo)))
		if err != nil {
			return "", "", false, err
		}
		return real, redactURL(repoURL) + "#" + inRepo, true, nil
	case strings.HasPrefix(r.source, "https://"), strings.HasPrefix(r.source, "http://"):
		return "", "", false, errors.New("an https manifest source has no file beside it; use a local or git+ source")
	}
	path = filepath.Join(filepath.Dir(r.source), rel)
	return path, path, false, nil
}

// resolveWithin follows symlinks in path and requires the result to stay under
// root: a manifest repository must not point a directory link out of its clone.
// A path that does not exist is returned as is, for the caller to report.
func resolveWithin(root, path string) (string, error) {
	realRoot, err := filepath.EvalSymlinks(root)
	if errors.Is(err, fs.ErrNotExist) {
		return path, nil
	}
	if err != nil {
		return "", err
	}
	real, err := filepath.EvalSymlinks(path)
	if errors.Is(err, fs.ErrNotExist) {
		return path, nil
	}
	if err != nil {
		return "", err
	}
	if rel, err := filepath.Rel(realRoot, real); err != nil || rel == ".." || strings.HasPrefix(rel, ".."+string(filepath.Separator)) {
		return "", errors.New("resolves outside the manifest repository")
	}
	return real, nil
}

// redactURL drops credentials from a URL shown in a generated file.
func redactURL(raw string) string {
	u, err := url.Parse(raw)
	if err != nil || u.User == nil {
		return raw
	}
	u.User = nil
	return u.String()
}

func readSourceFile(path string, strict bool) ([]byte, error) {
	stat := os.Stat
	if strict {
		stat = os.Lstat
	}
	fi, err := stat(path)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		return nil, errors.New("not found")
	case err != nil:
		return nil, err
	case !fi.Mode().IsRegular():
		return nil, errors.New("not a regular file")
	case fi.Size() > maxManifestBytes:
		return nil, fmt.Errorf("larger than %d bytes", maxManifestBytes)
	}
	return os.ReadFile(path)
}

// --- project shell ----------------------------------------------------------

func (s *Service) syncShell(r *run, res *SetupResult) {
	dst := devshell.ProjectShellPath(r.dir)
	p := r.manifest.Project
	if len(p.Packages) == 0 {
		s.removeGenerated(dst, devshell.ProjectShellRel, devshell.ProjectShellMarker, res)
		return
	}
	s.writeGenerated(dst, devshell.ProjectShellRel, devshell.ProjectShellMarker, []byte(devshell.ProjectScript(p.Nixpkgs, p.Packages)), 0o755, res)
	if _, err := exec.LookPath("nix"); err != nil {
		res.Warnings = append(res.Warnings, "project.packages need nix, which is not on PATH: panes, tasks and services run without them")
	}
}

// --- generated files --------------------------------------------------------

// isGenerated reports whether the file at path carries marker in its first two lines.
func isGenerated(path, marker string) bool {
	b, err := os.ReadFile(path)
	if err != nil {
		return false
	}
	lines := strings.SplitN(string(b), "\n", 3)
	for _, l := range lines[:min(2, len(lines))] {
		if strings.HasPrefix(l, marker) {
			return true
		}
	}
	return false
}

// writeGenerated writes data to dst unless it already holds exactly that. A
// file without ADE's marker is somebody's own and is left alone with a warning.
func (s *Service) writeGenerated(dst, rel, marker string, data []byte, perm os.FileMode, res *SetupResult) {
	if exists(dst) && !isGenerated(dst, marker) {
		res.Warnings = append(res.Warnings, fmt.Sprintf("%s exists and was not generated by ADE: left alone", rel))
		return
	}
	changed, err := writeIfChanged(dst, data, perm)
	switch {
	case err != nil:
		res.Warnings = append(res.Warnings, fmt.Sprintf("write %s: %v", rel, err))
	case changed:
		res.Written = append(res.Written, rel)
	}
}

// removeGenerated deletes a generated file whose manifest key is gone.
func (s *Service) removeGenerated(dst, rel, marker string, res *SetupResult) {
	if !isGenerated(dst, marker) {
		return
	}
	if err := os.Remove(dst); err != nil {
		res.Warnings = append(res.Warnings, fmt.Sprintf("remove %s: %v", rel, err))
		return
	}
	res.Removed = append(res.Removed, rel)
}

// writeIfChanged atomically writes data to path with perm and reports whether
// the file changed; identical content is not rewritten.
func writeIfChanged(path string, data []byte, perm os.FileMode) (bool, error) {
	if old, err := os.ReadFile(path); err == nil && bytes.Equal(old, data) {
		if fi, err := os.Stat(path); err == nil && fi.Mode().Perm() != perm {
			return false, os.Chmod(path, perm)
		}
		return false, nil
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return false, err
	}
	tmp, err := os.CreateTemp(filepath.Dir(path), filepath.Base(path)+".tmp*")
	if err != nil {
		return false, err
	}
	defer os.Remove(tmp.Name()) //nolint:errcheck // gone after a successful rename
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return false, err
	}
	if err := tmp.Close(); err != nil {
		return false, err
	}
	if err := os.Chmod(tmp.Name(), perm); err != nil {
		return false, err
	}
	return true, os.Rename(tmp.Name(), path)
}

// --- status -----------------------------------------------------------------

// setupStatus inspects the project-wide files on disk; nil when the manifest
// sets none.
func setupStatus(dir, source string, m *config.Manifest) *SetupStatus {
	p := m.Project
	var st SetupStatus
	if p.Agents != "" {
		file := filepath.Join(dir, AgentsFile)
		a := &AgentsStatus{Source: p.Agents, File: file, Written: isGenerated(file, agentsMarker)}
		if strings.HasPrefix(source, "https://") || strings.HasPrefix(source, "http://") {
			a.Note = "an https manifest source has no file beside it: not written"
		}
		st.Agents = a
	}
	if len(p.Packages) > 0 {
		file := devshell.ProjectShellPath(dir)
		sh := &ShellStatus{File: file, Packages: p.Packages, Nixpkgs: p.Nixpkgs, Written: isGenerated(file, devshell.ProjectShellMarker)}
		if _, err := exec.LookPath("nix"); err != nil {
			sh.Note = "nix is not on PATH: panes, tasks and services run without these packages"
		}
		st.Shell = sh
	}
	if reflect.DeepEqual(st, SetupStatus{}) {
		return nil
	}
	return &st
}
