// Repo groups (`[repo_groups]` in the manifest) are display only. The one file
// they generate is <root>/<project>/<workspace>.code-workspace for a group that
// names a workspace; the project directory is not a git tree, and repoDirs
// only counts directories holding a .bare, so these files are never repos.

// groupMarkerKey is the top-level key of a generated group workspace. ADE only
// rewrites or removes a file that carries it; VS Code ignores unknown keys.
const groupMarkerKey = "ade"

// groupMarker names the group and the file ADE wrote, so a copy of a generated
// file under another name (a user's own variant) is never taken for ADE's.
type groupMarker struct {
	RepoGroup string `json:"repo_group"`
	File      string `json:"file"`
}

// GroupWorkspacePath is the file a group's workspace is written to.
func GroupWorkspacePath(projectDir string, g config.RepoGroup) string {
	return filepath.Join(projectDir, g.Workspace+codews.Ext)
}

// GroupFolders lists the baseline worktree of every repo of the group, in the
// order the manifest names them. A repo that is not cloned yet is an error.
func GroupFolders(ctx context.Context, projectDir string, m *config.Manifest, group string) ([]codews.Folder, error) {
	g, ok := m.RepoGroups[group]
	if !ok {
		return nil, fmt.Errorf("no repo group %q in the manifest (have: %s)", group, groupNames(m))
	}
	folders := make([]codews.Folder, 0, len(g.Repos))
	for _, repo := range g.Repos {
		base, err := baselinePath(ctx, projectDir, repo, m.Repos[repo])
		if err != nil {
			return nil, err
		}
		folders = append(folders, codews.Folder{Name: codews.FolderName(repo, base), Path: base})
	}
	return folders, nil
}

func groupNames(m *config.Manifest) string {
	names := slices.Sorted(maps.Keys(m.RepoGroups))
	if len(names) == 0 {
		return "none"
	}
	return strings.Join(names, ", ")
}

// baselinePath is the repo's baseline worktree, named after its default branch.
func baselinePath(ctx context.Context, projectDir, repo string, spec config.Repo) (string, error) {
	repoDir := filepath.Join(projectDir, repo)
	def := spec.DefaultBranch
	if def == "" {
		var err error
		if def, err = (git.Client{}).DefaultBranch(ctx, filepath.Join(repoDir, ".bare")); err != nil {
			return "", fmt.Errorf("%s: default branch: %w", repo, err)
		}
	}
	dir := filepath.Join(repoDir, git.BranchDir(def))
	if !exists(dir) {
		return "", fmt.Errorf("baseline tree of %s is missing (%s): run `ade project add`", repo, dir)
	}
	return dir, nil
}

// WriteGroupWorkspace regenerates the group's workspace file and reports
// whether it changed. Folders and ADE's settings are regenerated; everything
// else in an existing generated file survives. A file ADE did not generate is
// an error, never overwritten.
func WriteGroupWorkspace(ctx context.Context, projectDir string, m *config.Manifest, group string) (path string, folders []codews.Folder, changed bool, err error) {
	g, ok := m.RepoGroups[group]
	if !ok {
		return "", nil, false, fmt.Errorf("no repo group %q in the manifest (have: %s)", group, groupNames(m))
	}
	if g.Workspace == "" {
		return "", nil, false, fmt.Errorf("repo group %q has no workspace name (set repo_groups.%s.workspace)", group, group)
	}
	if folders, err = GroupFolders(ctx, projectDir, m, group); err != nil {
		return "", nil, false, err
	}
	path = GroupWorkspacePath(projectDir, g)
	existing, err := os.ReadFile(path)
	switch {
	case errors.Is(err, fs.ErrNotExist):
		existing = nil
	case err != nil:
		return path, folders, false, err
	default:
		if _, gerr := generatedGroup(existing, filepath.Base(path)); gerr != nil {
			return path, folders, false, gerr
		}
	}
	data, err := codews.Merge(existing, folders, func(rest map[string]json.RawMessage) error {
		return codews.SetRaw(rest, groupMarkerKey, groupMarker{RepoGroup: group, File: filepath.Base(path)})
	})
	if err != nil {
		return path, folders, false, fmt.Errorf("%s: %w", path, err)
	}
	changed, err = writeIfChanged(path, data, 0o644)
	return path, folders, changed, err
}

// errNotGenerated marks a workspace file ADE did not write under that name.
var errNotGenerated = errors.New("exists and was not generated by ADE: left alone")

// generatedGroup returns the group the workspace file named file was generated
// for. It is an error when ADE did not write it under that name, or when it is
// no longer plain JSON (VS Code allows comments; ADE cannot merge them).
func generatedGroup(data []byte, file string) (string, error) {
	var top map[string]json.RawMessage
	if err := json.Unmarshal(data, &top); err != nil {
		if strings.Contains(string(data), `"repo_group"`) {
			return "", fmt.Errorf("%s is not plain JSON (comments?): ADE cannot regenerate it; remove the comments or the file", file)
		}
		return "", fmt.Errorf("%s %w", file, errNotGenerated)
	}
	var mk groupMarker
	if json.Unmarshal(top[groupMarkerKey], &mk) != nil || mk.RepoGroup == "" || mk.File != file {
		return "", fmt.Errorf("%s %w", file, errNotGenerated)
	}
	return mk.RepoGroup, nil
}

// syncGroups writes the workspace file of every group that names one and
// removes generated group files whose group or workspace key is gone.
func (s *Service) syncGroups(ctx context.Context, r *run, res *SetupResult) {
	wanted := map[string]bool{}
	for _, name := range slices.Sorted(maps.Keys(r.manifest.RepoGroups)) {
		g := r.manifest.RepoGroups[name]
		if g.Workspace == "" {
			continue
		}
		file := g.Workspace + codews.Ext
		wanted[file] = true
		_, _, changed, err := WriteGroupWorkspace(ctx, r.dir, r.manifest, name)
		switch {
		case err != nil:
			res.Warnings = append(res.Warnings, fmt.Sprintf("repo_groups.%s: %v", name, err))
		case changed:
			res.Written = append(res.Written, file)
		}
	}
	entries, err := os.ReadDir(r.dir)
	if err != nil {
		return
	}
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), codews.Ext) || wanted[e.Name()] {
			continue
		}
		path := filepath.Join(r.dir, e.Name())
		data, err := os.ReadFile(path)
		if err != nil {
			continue
		}
		if _, err := generatedGroup(data, e.Name()); err != nil {
			if !errors.Is(err, errNotGenerated) {
				res.Warnings = append(res.Warnings, err.Error())
			}
			continue
		}
		if err := os.Remove(path); err != nil {
			res.Warnings = append(res.Warnings, fmt.Sprintf("remove %s: %v", e.Name(), err))
			continue
		}
		res.Removed = append(res.Removed, e.Name())
	}
}
