// withProject rewrites the manifest at src to carry a [project] table. The
// table goes first, as TOML requires for keys before any [repos.*] table.
func withProject(t *testing.T, src, table string) {
	t.Helper()
	b, err := os.ReadFile(src)
	if err != nil {
		t.Fatal(err)
	}
	name, rest, _ := strings.Cut(string(b), "\n")
	if err := os.WriteFile(src, []byte(name+"\n"+table+"\n"+rest), 0o644); err != nil {
		t.Fatal(err)
	}
}

func readFile(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func TestAddWritesRewritesAndRemovesProjectAgents(t *testing.T) {
	e := newEnv(t)
	r := newRemote(t, "api")
	src := e.manifest("demo", map[string]*remote{"api": r}, nil)
	guidance := filepath.Join(filepath.Dir(src), "TEAM.md")
	if err := os.WriteFile(guidance, []byte("Use tabs.\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	withProject(t, src, "[project]\nagents = \"TEAM.md\"\n")
	agents := filepath.Join(e.app.Root, "demo", "AGENTS.md")

	rep, err := e.svc.Add(context.Background(), src)
	if err != nil || rep.Failed() {
		t.Fatalf("add: %v %+v", err, rep)
	}
	got := readFile(t, agents)
	if !strings.HasPrefix(got, "<!-- Generated by ADE") || !strings.Contains(got, guidance) || !strings.HasSuffix(got, "\n\nUse tabs.\n") {
		t.Fatalf("AGENTS.md:\n%s", got)
	}
	if len(rep.Setup) != 1 || len(rep.Setup[0].Written) != 1 || rep.Setup[0].Written[0] != "AGENTS.md" {
		t.Errorf("setup = %+v", rep.Setup)
	}
	if ReadAgents(filepath.Join(e.app.Root, "demo")) != "Use tabs." {
		t.Errorf("ReadAgents = %q", ReadAgents(filepath.Join(e.app.Root, "demo")))
	}

	// Unchanged: nothing is rewritten or reported.
	rep, err = e.svc.Update(context.Background())
	if err != nil || len(rep.Setup) != 0 {
		t.Fatalf("idempotent update: %v %+v", err, rep.Setup)
	}

	// A changed source is rewritten.
	if err := os.WriteFile(guidance, []byte("Use spaces.\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if rep, err = e.svc.Update(context.Background()); err != nil || len(rep.Setup) != 1 {
		t.Fatalf("update: %v %+v", err, rep.Setup)
	}
	if !strings.HasSuffix(readFile(t, agents), "Use spaces.\n") {
		t.Errorf("AGENTS.md not rewritten:\n%s", readFile(t, agents))
	}

	// The key goes away: the generated file goes with it.
	if err := os.WriteFile(src, []byte(strings.Replace(readFile(t, src), "[project]\nagents = \"TEAM.md\"\n", "", 1)), 0o644); err != nil {
		t.Fatal(err)
	}
	rep, err = e.svc.Update(context.Background())
	if err != nil || exists(agents) || len(rep.Setup) != 1 || rep.Setup[0].Removed[0] != "AGENTS.md" {
		t.Fatalf("remove: %v %+v exists=%v", err, rep.Setup, exists(agents))
	}
}

func TestProjectAgentsLeavesAHandWrittenFileAlone(t *testing.T) {
	e := newEnv(t)
	r := newRemote(t, "api")
	src := e.manifest("demo", map[string]*remote{"api": r}, nil)
	if err := os.WriteFile(filepath.Join(filepath.Dir(src), "TEAM.md"), []byte("x\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	withProject(t, src, "[project]\nagents = \"TEAM.md\"\n")
	own := filepath.Join(e.app.Root, "demo", "AGENTS.md")
	if err := os.MkdirAll(filepath.Dir(own), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(own, []byte("mine\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	rep, err := e.svc.Add(context.Background(), src)
	if err != nil || readFile(t, own) != "mine\n" {
		t.Fatalf("add: %v, file %q", err, readFile(t, own))
	}
	if len(rep.Setup) != 1 || !strings.Contains(strings.Join(rep.Setup[0].Warnings, "\n"), "not generated by ADE") {
		t.Errorf("setup = %+v", rep.Setup)
	}
}

