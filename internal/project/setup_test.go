func TestProjectAgentsFromGitManifestSource(t *testing.T) {
	e := newEnv(t)
	api := newRemote(t, "api")
	tracker := newRemote(t, "tracker")
	manifest := e.manifest("demo", map[string]*remote{"api": api}, nil)
	withProject(t, manifest, "[project]\nagents = \"AGENTS.md\"\n")
	tracker.commit(".ade.toml", readFile(t, manifest))
	tracker.commit("AGENTS.md", "Team rules.\n")
	tracker.push("main")

	rep, err := e.svc.Add(context.Background(), "git+"+tracker.url()+"#.ade.toml")
	if err != nil || rep.Failed() {
		t.Fatalf("add: %v %+v", err, rep)
	}
	got := readFile(t, filepath.Join(e.app.Root, "demo", "AGENTS.md"))
	if !strings.Contains(got, tracker.url()+"#AGENTS.md") || !strings.HasSuffix(got, "Team rules.\n") {
		t.Errorf("AGENTS.md:\n%s", got)
	}
}

