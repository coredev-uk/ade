func TestProjectShellIsWrittenAndRemoved(t *testing.T) {
	e := newEnv(t)
	// The script is written whether or not nix exists; a stub keeps the
	// missing-nix warning (its own test) out of the idempotence check.
	stub := t.TempDir()
	if err := os.WriteFile(filepath.Join(stub, "nix"), []byte("#!/bin/sh\nexit 0\n"), 0o755); err != nil {
		t.Fatal(err)
	}
	t.Setenv("PATH", stub+string(os.PathListSeparator)+os.Getenv("PATH"))
	r := newRemote(t, "api")
	src := e.manifest("demo", map[string]*remote{"api": r}, nil)
	withProject(t, src, "[project]\npackages = [\"nodejs_22\", \"pnpm\"]\nnixpkgs = \"github:NixOS/nixpkgs/nixos-25.05\"\n")
	script := devshell.ProjectShellPath(filepath.Join(e.app.Root, "demo"))

	if _, err := e.svc.Add(context.Background(), src); err != nil {
		t.Fatal(err)
	}
	fi, err := os.Stat(script)
	if err != nil || fi.Mode().Perm() != 0o755 {
		t.Fatalf("script: %v %v", fi, err)
	}
	if got := readFile(t, script); got != devshell.ProjectScript("github:NixOS/nixpkgs/nixos-25.05", []string{"nodejs_22", "pnpm"}) {
		t.Errorf("script:\n%s", got)
	}
	if rep, err := e.svc.Update(context.Background()); err != nil || len(rep.Setup) != 0 {
		t.Errorf("idempotent update: %v %+v", err, rep.Setup)
	}

	e.manifest("demo", map[string]*remote{"api": r}, nil) // rewrites the file without [project]
	withProject(t, src, "[project]\npackages = [\"go\"]")
	if _, err := e.svc.Update(context.Background()); err != nil || !strings.Contains(readFile(t, script), "'nixpkgs#go'") {
		t.Fatalf("rewrite: %v\n%s", err, readFile(t, script))
	}

	if err := os.WriteFile(src, []byte("name = \"demo\"\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if _, err := e.svc.Update(context.Background()); err != nil || exists(script) {
		t.Fatalf("the script must go with its key: %v exists=%v", err, exists(script))
	}
}

func TestProjectShellWarnsWithoutNix(t *testing.T) {
	e := newEnv(t)
	r := newRemote(t, "api")
	src := e.manifest("demo", map[string]*remote{"api": r}, nil)
	withProject(t, src, "[project]\npackages = [\"go\"]\n")
	if _, err := e.svc.Add(context.Background(), src); err != nil {
		t.Fatal(err)
	}
	// git stays reachable through its absolute path in newEnv's PATH-less lookups
	gitDir := filepath.Dir(lookGit(t))
	t.Setenv("PATH", gitDir)
	r2 := &run{name: "demo", dir: filepath.Join(e.app.Root, "demo"), manifest: mustParse(t, "name = \"demo\"\n[project]\npackages = [\"go\"]\n")}
	var res SetupResult
	e.svc.syncShell(r2, &res)
	if len(res.Warnings) != 1 || !strings.Contains(res.Warnings[0], "nix") {
		t.Errorf("warnings = %v", res.Warnings)
	}
	st := setupStatus(r2.dir, "", r2.manifest)
	if st.Shell == nil || !strings.Contains(st.Shell.Note, "nix is not on PATH") {
		t.Errorf("status = %+v", st.Shell)
	}
}

// The generated files sit in the project directory next to the repos; `ade project status` must not mistake them for dropped repos.
func TestSetupFilesAreNotReposInStatus(t *testing.T) {
	e := newEnv(t)
	api := newRemote(t, "api")
	src := e.manifest("demo", map[string]*remote{"api": api}, nil)
	if err := os.WriteFile(filepath.Join(filepath.Dir(src), "TEAM.md"), []byte("x\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	withProject(t, src, "[project]\nagents = \"TEAM.md\"\npackages = [\"go\"]\n")
	if rep, err := e.svc.Add(context.Background(), src); err != nil || rep.Failed() {
		t.Fatalf("add: %v %+v", err, rep)
	}
	sts, err := e.svc.Status(context.Background(), "demo")
	if err != nil || len(sts) != 1 {
		t.Fatalf("status: %v %+v", err, sts)
	}
	if len(sts[0].Repos) != 1 || sts[0].Repos[0].Name != "api" {
		t.Errorf("repos = %+v", sts[0].Repos)
	}
	su := sts[0].Setup
	if su == nil || su.Agents == nil || !su.Agents.Written || su.Shell == nil || !su.Shell.Written {
		t.Fatalf("setup = %+v", su)
	}
}

func mustParse(t *testing.T, src string) *config.Manifest {
	t.Helper()
	m, err := config.ParseManifest([]byte(src), "test.ade.toml")
	if err != nil {
		t.Fatal(err)
	}
	return m
}

func lookGit(t *testing.T) string {
	t.Helper()
	p, err := exec.LookPath("git")
	if err != nil {
		t.Skip("git is not installed")
	}
	return p
}

func TestResolveWithinRefusesAnEscapingSymlink(t *testing.T) {
	dir := t.TempDir()
	clone, outside := filepath.Join(dir, "clone"), filepath.Join(dir, "outside")
	for _, d := range []string{filepath.Join(clone, "docs"), outside} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			t.Fatal(err)
		}
	}
	for _, f := range []string{filepath.Join(clone, "docs", "A.md"), filepath.Join(outside, "A.md")} {
		if err := os.WriteFile(f, []byte("x"), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.Symlink(outside, filepath.Join(clone, "link")); err != nil {
		t.Fatal(err)
	}
	if _, err := resolveWithin(clone, filepath.Join(clone, "link", "A.md")); err == nil {
		t.Error("a symlinked directory leading out of the clone was followed")
	}
	if _, err := resolveWithin(clone, filepath.Join(clone, "docs", "A.md")); err != nil {
		t.Errorf("inside: %v", err)
	}
	if got, err := resolveWithin(clone, filepath.Join(clone, "docs", "NOPE.md")); err != nil || got != filepath.Join(clone, "docs", "NOPE.md") {
		t.Errorf("missing file: %q %v", got, err)
	}
}

// Setup writes count as changes and its warnings as warnings.
func TestReportCountsProjectSetup(t *testing.T) {
	quiet := Report{Setup: []SetupResult{{Project: "demo", Warnings: []string{"x"}}}}
	if quiet.Changed() || quiet.Severity() != events.Warn || quiet.Title() != "1 setup warning" {
		t.Errorf("warnings only: changed=%v severity=%v title=%q", quiet.Changed(), quiet.Severity(), quiet.Title())
	}
	wrote := Report{Setup: []SetupResult{{Project: "demo", Written: []string{"AGENTS.md"}, Removed: []string{".ade/shell"}}}}
	if !wrote.Changed() || wrote.Severity() != events.Success || wrote.Title() != "updated 2 project files" {
		t.Errorf("writes: changed=%v severity=%v title=%q", wrote.Changed(), wrote.Severity(), wrote.Title())
	}
}
