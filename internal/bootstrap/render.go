// RepoFinding is one code repository of the draft and what was learnt of it.
type RepoFinding struct {
	Key           string // name in [repos.<key>]
	Path          string // forge path
	DefaultBranch string
	Apps          []string // app-label values routed here
	AppMatched    bool     // false: the repo name is a guess, no app label matched it
	Detected      Detected
	Templates     []string // MR template names found on the default branch
}

// Draft is a manifest with the reasons behind each choice. Render writes it
// as TOML; everything in Manifest is also in the text, nothing else is.
type Draft struct {
	Manifest config.Manifest
	Group    string
	Tracker  forge.Repo

	TrackerWhy    string
	IterationsWhy []string // comment lines for tracker.iterations
	WeightWhy     []string
	TypeWhy       string
	AppWhy        string
	WorkflowWhy   []string
	Repos         []RepoFinding
	KeyPrefix     string   // shared repo-name prefix dropped from the keys
	Skipped       []string // repos left out, with the reason
	Notes         []string // what the run found, for the terminal
	Cadence       string   // chosen iteration cadence, when several exist
	TOML          string   // the rendered manifest; Discover fills it
}

// TOML string literal: basic string with the escapes the spec requires.
func quote(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch {
		case r == '"':
			b.WriteString(`\"`)
		case r == '\\':
			b.WriteString(`\\`)
		case r == '\n':
			b.WriteString(`\n`)
		case r == '\t':
			b.WriteString(`\t`)
		case r < 0x20 || r == 0x7f:
			fmt.Fprintf(&b, `\u%04X`, r)
		default:
			b.WriteRune(r)
		}
	}
	b.WriteByte('"')
	return b.String()
}

func quoteList(vs []string) string {
	q := make([]string, len(vs))
	for i, v := range vs {
		q[i] = quote(v)
	}
	return "[" + strings.Join(q, ", ") + "]"
}

// inline renders {k = "v", ...} with keys in the given order.
func inline(pairs ...[2]string) string {
	parts := make([]string, len(pairs))
	for i, p := range pairs {
		parts[i] = p[0] + " = " + p[1]
	}
	return "{ " + strings.Join(parts, ", ") + " }"
}

type writer struct{ strings.Builder }

func (w *writer) line(format string, args ...any) { fmt.Fprintf(&w.Builder, format+"\n", args...) }

// oneLine makes text safe inside a TOML comment: forge-supplied titles and
// label values must not end the comment and start a setting.
func oneLine(s string) string {
	return strings.Map(func(r rune) rune {
		if r < 0x20 || r == 0x7f || r == 0x2028 || r == 0x2029 {
			return ' '
		}
		return r
	}, s)
}

// kv writes `key = value` with an optional trailing comment, aligning values
// of one block at col.
func (w *writer) kv(col int, key, value, comment string) {
	s := fmt.Sprintf("%-*s = %s", col, key, value)
	if comment != "" {
		s += "   # " + oneLine(comment)
	}
	w.line("%s", s)
}

func (w *writer) comment(lines ...string) {
	for _, l := range lines {
		if l == "" {
			w.line("#")
			continue
		}
		w.line("# %s", oneLine(l))
	}
}

// Render writes the draft as TOML with a comment for every decision.
func (d *Draft) Render() string {
	m := &d.Manifest
	var w writer
	w.comment(
		fmt.Sprintf("ADE project manifest for %s, generated by `ade project bootstrap`", d.Group),
		"from the forge group's repositories, labels, iterations and root files. Review it, then commit it to the",
		"tracker repository (docs/manifest.md). Comments above a setting say how it was detected; commented-out",
		"settings are suggestions the forge could not settle.",
		"",
	)
	w.kv(5, "name", quote(m.Name), "path-safe project name: becomes the directory under your projects root")
	w.kv(5, "forge", quote(m.Forge), "key into each person's user config [forges]; everyone must use this name")
	w.line("")

	w.line("[tracker]")
	w.kv(10, "project", quote(m.Tracker.Project), d.TrackerWhy)
	w.comment(d.IterationsWhy...)
	w.kv(10, "iterations", iterationsInline(m.Tracker.Iterations), "")
	w.comment(d.WeightWhy...)
	w.kv(10, "weight", weightInline(m.Tracker.Weight), "")
	w.line("")

	d.renderLabels(&w)
	d.renderRepos(&w)
	d.renderConventions(&w)
	d.renderGroups(&w)
	return w.String()
}

func iterationsInline(it config.IterationsSource) string {
	pairs := [][2]string{{"source", quote(it.Source)}}
	if it.Cadence != "" {
		pairs = append(pairs, [2]string{"cadence", quote(it.Cadence)})
	}
	if it.Pattern != "" {
		pairs = append(pairs, [2]string{"pattern", quote(it.Pattern)})
	}
	if it.Start != "" {
		pairs = append(pairs, [2]string{"start", quote(it.Start)})
	}
	if it.Length != "" {
		pairs = append(pairs, [2]string{"length", quote(it.Length)})
	}
	return inline(pairs...)
}

func weightInline(wt config.WeightSource) string {
	pairs := [][2]string{{"source", quote(wt.Source)}}
	if wt.Pattern != "" {
		pairs = append(pairs, [2]string{"pattern", quote(wt.Pattern)})
	}
	if wt.Field != "" {
		pairs = append(pairs, [2]string{"field", quote(wt.Field)})
	}
	return inline(pairs...)
}

func (d *Draft) renderLabels(w *writer) {
	l := d.Manifest.Labels
	facet := func(name, pattern, why, example string) {
		if pattern == "" {
			w.comment("["+"labels."+name+"]", "pattern = "+quote(example)+"   # "+why)
			w.line("")
			return
		}
		w.line("[labels.%s]", name)
		w.kv(7, "pattern", quote(pattern), why)
		w.line("")
	}
	facet("type", l.Type.Pattern, d.TypeWhy, "type::{value}")
	facet("app", l.App.Pattern, d.AppWhy, "app::{value}")

	if l.Workflow.Pattern == "" {
		w.comment("[labels.workflow]", `pattern = "workflow::{value}"   # no workflow labels found`,
			`stage   = { started = "in progress", review = "in review", merged = "done" }`, "")
		return
	}
	w.line("[labels.workflow]")
	w.comment(d.WorkflowWhy...)
	w.kv(7, "pattern", quote(l.Workflow.Pattern), "")
	var stages [][2]string
	for _, s := range []string{stageStarted, stageDraft, stageReview, stageMerged} {
		if v, ok := l.Workflow.Stage[s]; ok {
			stages = append(stages, [2]string{s, quote(v)})
		}
	}
	if len(stages) > 0 {
		w.kv(7, "stage", inline(stages...), "ADE's derived stage -> your board column")
	}
	w.kv(7, "sync", quote(l.Workflow.Sync), `auto moves the label when the stage changes; "ask" confirms each move, "off" only shows drift`)
	if l.Workflow.Done != "" {
		w.kv(7, "done", quote(l.Workflow.Done), "an open tracker issue with this value counts as done; remove if you close issues when work ends")
	}
	w.line("")
}

func (d *Draft) renderRepos(w *writer) {
	if len(d.Repos) == 0 {
		w.comment("No code repositories were found next to the tracker: add [repos.<name>] tables by hand.", "")
		return
	}
	w.comment(
		"Repositories of the group. `app` lists the values of the app label that route a tracker issue here.",
		"The tracker repository is not listed: add a [repos.<name>] table for it if code is worked on there too.",
		`Add requires = ["<repo>"] to a repo that needs another checked out beside it (web needs api).`,
	)
	if d.KeyPrefix != "" {
		w.comment(fmt.Sprintf("Repo names drop the shared prefix %q.", d.KeyPrefix))
	}
	w.line("")
	for _, r := range d.Repos {
		w.line("[repos.%s]", r.Key)
		w.kv(4, "path", quote(r.Path), branchNote(r.DefaultBranch))
		w.kv(4, "app", quoteList(r.Apps), appNote(r, d.Manifest.Labels.App.Pattern != ""))
		w.line("")
		for _, t := range r.Detected.Tasks {
			renderTask(w, "repos."+r.Key+".tasks."+t.Name, t)
		}
		if len(r.Detected.Hints) > 0 {
			for _, h := range r.Detected.Hints {
				w.comment(r.Key + ": " + h)
			}
			w.line("")
		}
	}
}

func branchNote(branch string) string {
	if branch == "" || branch == "main" {
		return ""
	}
	return "default branch " + branch + " (detected from the clone; no setting needed)"
}

func appNote(r RepoFinding, haveFacet bool) string {
	switch {
	case !haveFacet:
		return "no app labels found: the repo name stands in for the value"
	case !r.AppMatched:
		return "no app label value matches this repo: its name is a guess"
	}
	return ""
}

func renderTask(w *writer, table string, t NamedTask) {
	w.line("[%s]", table)
	w.kv(8, "cmd", quote(t.Task.Cmd), "from "+t.From)
	if t.Task.Kind != "" {
		w.kv(8, "kind", quote(t.Task.Kind), "")
	}
	if t.Task.Port.Auto {
		w.kv(8, "port", quote("auto"), "")
	} else if t.Task.Port.Fixed > 0 {
		w.kv(8, "port", strconv.Itoa(t.Task.Port.Fixed), "")
	}
	if len(t.Task.Requires) > 0 {
		w.kv(8, "requires", quoteList(t.Task.Requires), "")
	}
	if len(t.Task.Env) > 0 {
		var pairs [][2]string
		for _, k := range envKeys(t.Task.Env) {
			pairs = append(pairs, [2]string{k, quote(t.Task.Env[k])})
		}
		w.kv(8, "env", inline(pairs...), "")
	}
	w.line("")
}

func (d *Draft) renderConventions(w *writer) {
	w.line("[conventions]")
	w.kv(11, "child_issue", quote(d.Manifest.Conventions.ChildIssue), "auto: a child issue in the code repo when the tracker is another project")
	w.comment(
		"Start-work conventions you may set (docs/manifest.md): branch, child_title, child_body, link and mr, e.g.",
		`branch = "{child_iid}-{slug}"`,
		`mr     = { create = "ask", draft = true, closes = "child", mention = "parent" }`,
		`commit_prefix = "GL-{parent}"   # prefix commit and merge messages with the tracker issue`,
	)
	for _, n := range d.templateNotes() {
		w.comment(n)
	}
	w.line("")
}

// templateNotes says which MR templates the repos carry and the one-line
// setting that picks one.
func (d *Draft) templateNotes() []string {
	var withTemplates, without []string
	names := map[string]int{}
	for _, r := range d.Repos {
		if len(r.Templates) == 0 {
			without = append(without, r.Key)
			continue
		}
		withTemplates = append(withTemplates, r.Key)
		for _, t := range r.Templates {
			names[t]++
		}
	}
	if len(withTemplates) == 0 {
		return []string{"No MR templates found on the repos' default branches."}
	}
	notes := []string{fmt.Sprintf("MR templates found in: %s.", strings.Join(withTemplates, ", "))}
	if len(without) > 0 {
		notes = append(notes, fmt.Sprintf("No MR template in: %s.", strings.Join(without, ", ")))
	}
	if len(names) == 1 {
		for n := range names {
			notes = append(notes, "mr = { template = "+quote(n)+" }   # pick it explicitly if you want")
		}
	}
	return notes
}

func (d *Draft) renderGroups(w *writer) {
	var dev []string
	for _, r := range d.Repos {
		for _, t := range r.Detected.Dev {
			dev = append(dev, r.Key+"."+t)
		}
	}
	if len(dev) == 0 {
		w.comment(
			"No dev tasks were detected, so there is no run group yet. With tasks, a group names what `ade ws up` starts:",
			`[groups]`, `dev = ["web.dev"]`, "",
			"[workspaces]", `default = { layout = "code", run = "dev" }`,
		)
		return
	}
	w.comment(
		"No ready probe is set, so dependents do not wait for a task: add ready = { http = \"http://localhost:{port}/<health path>\" }",
		"to a service that listens on {port} (see docs/manifest.md).",
	)
	w.line("[groups]")
	w.kv(3, "dev", quoteList(dev), "what `ade ws up` starts; requires between tasks pull in the rest")
	w.line("")
	w.line("[workspaces]")
	w.kv(7, "default", inline([2]string{"layout", quote("code")}, [2]string{"run", quote("dev")}), "")
}
