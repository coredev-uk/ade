package bootstrap

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"slices"

	"github.com/coredev-uk/ade/internal/forge"
)

// Publishing opens a merge request on the tracker repo that adds the manifest.
// Every step is idempotent: the branch has a fixed name, an identical file is
// not committed twice and an open MR is reused, so running it again after
// editing the draft updates the same MR.

// PublishBranch is the branch the manifest is committed to.
const PublishBranch = "ade/bootstrap-manifest"

// ManifestPath is where the manifest lives in the tracker repo.
const ManifestPath = ".ade.toml"

// PublishOptions control Publish.
type PublishOptions struct {
	DryRun bool
	// Force replaces a manifest already on the default branch (through the MR).
	Force bool
	// Audit records one forge write; nil skips auditing.
	Audit func(action, target string, params map[string]any, url string, err error)
}

// Published says what Publish did, or with DryRun, would do.
type Published struct {
	Project string    `json:"project"`
	Base    string    `json:"base"` // the tracker's default branch
	Branch  string    `json:"branch"`
	Path    string    `json:"path"`
	Title   string    `json:"title"`
	Body    string    `json:"body"`
	DryRun  bool      `json:"dry_run,omitempty"`
	Steps   []string  `json:"steps"`
	MR      *forge.MR `json:"mr,omitempty"`
	// Nothing is set when the default branch already carries this manifest.
	Nothing bool `json:"nothing,omitempty"`
}

// mrTitle and mrBody are what the merge request says. The body names how a
// teammate registers the manifest once it is merged.
const mrTitle = "Add the ADE project manifest (.ade.toml)"

func mrBody(project, source string) string {
	return fmt.Sprintf("Adds `%s`, generated by `ade project bootstrap` from the forge group: tracker, repos, label patterns, "+
		"iteration and weight sources and the run tasks detected in each repo's root files.\n\n"+
		"Review the comments in the file: detected settings are explained there, and commented-out ones need a decision.\n\n"+
		"After it merges, teammates register it with:\n\n```\nade init --project '%s'\n```\n", ManifestPath, source)
}

// Publish commits content to a branch of the tracker repo and opens (or
// finds) the merge request. gitSource is the git+<url>#<path> a teammate
// would register, for the MR body.
func Publish(ctx context.Context, f Forge, tracker string, content []byte, gitSource string, o PublishOptions) (Published, error) {
	p := Published{Project: tracker, Branch: PublishBranch, Path: ManifestPath, Title: mrTitle, Body: mrBody(tracker, gitSource), DryRun: o.DryRun}
	base, err := f.DefaultBranch(ctx, tracker)
	if err != nil {
		return p, fmt.Errorf("default branch of %s: %w", tracker, err)
	}
	p.Base = base

	onBase, err := f.ReadFile(ctx, tracker, base, ManifestPath)
	switch {
	case errors.Is(err, forge.ErrNotFound):
		// no manifest on the default branch yet
	case err != nil:
		return p, fmt.Errorf("reading %s on %s: %w", ManifestPath, base, err)
	case bytes.Equal(onBase, content):
		p.Nothing = true
		p.Steps = []string{fmt.Sprintf("%s on %s is already this manifest: nothing to publish", ManifestPath, base)}
		return p, nil
	case !o.Force:
		return p, fmt.Errorf("%s already exists on %s of %s with other content: --force proposes replacing it", ManifestPath, base, tracker)
	}

	branches, err := f.Branches(ctx, tracker, PublishBranch)
	if err != nil {
		return p, fmt.Errorf("branches of %s: %w", tracker, err)
	}
	haveBranch := slices.Contains(branches, PublishBranch)
	var onBranch []byte
	if haveBranch {
		onBranch, err = f.ReadFile(ctx, tracker, PublishBranch, ManifestPath)
		if err != nil && !errors.Is(err, forge.ErrNotFound) {
			return p, fmt.Errorf("reading %s on %s: %w", ManifestPath, PublishBranch, err)
		}
	}
	open, err := f.ListMRs(ctx, forge.MRQuery{Project: tracker, State: "opened", SourceBranch: PublishBranch})
	if err != nil {
		return p, fmt.Errorf("merge requests of %s: %w", tracker, err)
	}
	var existing *forge.MR
	if i := slices.IndexFunc(open, func(m forge.MR) bool { return m.TargetBranch == base }); i >= 0 {
		existing = &open[i]
	}

	commit := !haveBranch || !bytes.Equal(onBranch, content)
	p.Steps = planSteps(tracker, base, haveBranch, commit, existing)
	if o.DryRun {
		p.MR = existing
		return p, nil
	}

	audit := func(action, target string, params map[string]any, url string, err error) {
		if o.Audit != nil {
			o.Audit(action, target, params, url, err)
		}
	}
	if !haveBranch {
		b, err := f.CreateBranch(ctx, tracker, PublishBranch, base)
		audit("forge.branch.create", tracker+":"+PublishBranch, map[string]any{"from": base}, b.WebURL, err)
		if err != nil && !errors.Is(err, forge.ErrExists) {
			return p, fmt.Errorf("creating branch %s: %w", PublishBranch, err)
		}
	}
	if commit {
		err := f.CommitFile(ctx, tracker, PublishBranch, ManifestPath, content, "Add the ADE project manifest")
		audit("forge.file.commit", tracker+":"+PublishBranch, map[string]any{"path": ManifestPath, "bytes": len(content)}, "", err)
		if err != nil {
			return p, err
		}
	}
	if existing != nil {
		p.MR = existing
		return p, nil
	}
	mr, err := f.CreateMR(ctx, forge.MRDraft{
		Project: tracker, Source: PublishBranch, Target: base, Title: p.Title, Description: p.Body,
	})
	audit("forge.mr.create", mr.Ref.String(), map[string]any{"source": PublishBranch, "target": base}, mr.WebURL, err)
	if err != nil {
		return p, fmt.Errorf("opening the merge request: %w", err)
	}
	p.MR = &mr
	return p, nil
}

func planSteps(tracker, base string, haveBranch, commit bool, existing *forge.MR) []string {
	var steps []string
	if haveBranch {
		steps = append(steps, fmt.Sprintf("branch %s exists", PublishBranch))
	} else {
		steps = append(steps, fmt.Sprintf("create branch %s from %s", PublishBranch, base))
	}
	if commit {
		steps = append(steps, fmt.Sprintf("commit %s to %s", ManifestPath, PublishBranch))
	} else {
		steps = append(steps, fmt.Sprintf("%s on %s is up to date", ManifestPath, PublishBranch))
	}
	if existing != nil {
		steps = append(steps, fmt.Sprintf("merge request %s is open: reused", existing.Ref))
	} else {
		steps = append(steps, fmt.Sprintf("open a merge request %s -> %s on %s", PublishBranch, base, tracker))
	}
	return steps
}
