// TaskPrefix starts the label of every generated VS Code task. It is how a
// regenerated tasks.json tells ADE's tasks from the user's own.
const TaskPrefix = "ade: "

// ReadyMarker is printed by `ade task run` once a node is ready; the generated
// background problem matcher ends on it for http, tcp and probe-less nodes.
func ReadyMarker(node string) string { return "ade: ready " + node }

// StartMarker is printed by `ade task run` when it begins a node.
func StartMarker(node string) string { return "ade: starting " + node }

// VSTask is one entry of .vscode/tasks.json (schema 2.0.0).
type VSTask struct {
	Label          string         `json:"label"`
	Type           string         `json:"type"`
	Command        string         `json:"command,omitempty"`
	Args           []string       `json:"args,omitempty"`
	Options        *VSOptions     `json:"options,omitempty"`
	IsBackground   bool           `json:"isBackground,omitempty"`
	ProblemMatcher any            `json:"problemMatcher"`
	DependsOn      []string       `json:"dependsOn,omitempty"`
	DependsOrder   string         `json:"dependsOrder,omitempty"`
	Presentation   map[string]any `json:"presentation,omitempty"`
	Detail         string         `json:"detail,omitempty"`
}

// VSOptions are the cwd of a task.
type VSOptions struct {
	CWD string `json:"cwd"`
}

type vsMatcher struct {
	Owner      string       `json:"owner"`
	Pattern    vsPattern    `json:"pattern"`
	Background vsBackground `json:"background"`
}

type vsPattern struct {
	Regexp string `json:"regexp"`
}

type vsBackground struct {
	ActiveOnStart bool   `json:"activeOnStart"`
	BeginsPattern string `json:"beginsPattern"`
	EndsPattern   string `json:"endsPattern"`
}

// BuildTasks maps the run graph to VS Code tasks: one task per node whose
// dependsOn mirrors its requirements, plus a compound task that runs the
// workspace's roots. Services are background tasks that end their "active"
// state on the node's readiness; oneshots are ordinary tasks that finish on
// exit 0. runArgs are the extra `ade task run` arguments (tree pins).
func BuildTasks(p *Plan, ade string, runArgs []string) []VSTask {
	label := func(node string) string { return TaskPrefix + node }
	var tasks []VSTask
	for _, in := range p.Instances {
		n := in.Node
		t := VSTask{
			Label:   label(n.ID),
			Type:    "process",
			Command: ade,
			Args:    append([]string{"task", "run", n.ID, "--worktree", p.Loc.Tree}, runArgs...),
			Options: &VSOptions{CWD: in.Dir},
			Detail:  taskDetail(in),
		}
		for _, req := range n.Requires {
			t.DependsOn = append(t.DependsOn, label(req))
		}
		if n.Oneshot() {
			t.ProblemMatcher = []any{}
			t.Args = append(t.Args, "--no-follow")
		} else {
			t.IsBackground = true
			t.Presentation = map[string]any{"panel": "dedicated", "group": "ade"}
			t.ProblemMatcher = vsMatcher{
				Owner:   "ade",
				Pattern: vsPattern{Regexp: "^$"},
				Background: vsBackground{
					ActiveOnStart: true,
					BeginsPattern: "^" + regexp.QuoteMeta(StartMarker(n.ID)),
					EndsPattern:   endsPattern(in),
				},
			}
		}
		tasks = append(tasks, t)
	}
	if len(p.Roots) > 0 {
		all := VSTask{
			Label:          label("up"),
			Type:           "shell",
			Detail:         "Start the workspace's run graph (" + strings.Join(p.Roots, ", ") + ")",
			DependsOrder:   "parallel",
			ProblemMatcher: []any{},
		}
		for _, r := range p.Roots {
			all.DependsOn = append(all.DependsOn, label(r))
		}
		tasks = append(tasks, all)
	}
	return tasks
}

func taskDetail(in *Instance) string {
	d := "generated by ade; " + in.Node.ID
	if in.Ready != nil {
		d += ", ready: " + string(in.Ready.Kind)
	}
	return d
}

// endsPattern is what ends a background task's activity: the node's log regexp
// for log readiness, otherwise the marker `ade task run` prints on readiness.
func endsPattern(in *Instance) string {
	if in.Ready != nil && in.Ready.Kind == readiness.Log {
		return in.Ready.Target
	}
	return "^" + regexp.QuoteMeta(ReadyMarker(in.Node.ID))
}

// tasksFile is the layout of tasks.json that matters here; unknown top-level
// keys survive a rewrite.
type tasksFile struct {
	rest  map[string]json.RawMessage
	tasks []json.RawMessage
}

// TasksPath is where the export lives.
func TasksPath(worktree string) string { return filepath.Join(worktree, ".vscode", "tasks.json") }

// MergeTasks returns the tasks.json content for worktree: the existing file
// with every ADE-generated task replaced by tasks, other tasks and settings
// untouched. A file that is not plain JSON (VS Code allows comments) is an
// error rather than being overwritten.
func MergeTasks(existing []byte, tasks []VSTask) ([]byte, error) {
	f := tasksFile{rest: map[string]json.RawMessage{}}
	if len(bytes.TrimSpace(existing)) > 0 {
		if err := json.Unmarshal(existing, &f.rest); err != nil {
			return nil, fmt.Errorf("existing tasks.json is not plain JSON (comments?): %w", err)
		}
		if raw, ok := f.rest["tasks"]; ok {
			if err := json.Unmarshal(raw, &f.tasks); err != nil {
				return nil, fmt.Errorf("existing tasks.json: tasks: %w", err)
			}
		}
	}
	var keep []json.RawMessage
	for _, raw := range f.tasks {
		var probe struct {
			Label string `json:"label"`
		}
		if json.Unmarshal(raw, &probe) == nil && strings.HasPrefix(probe.Label, TaskPrefix) {
			continue
		}
		keep = append(keep, raw)
	}
	for _, t := range tasks {
		raw, err := json.Marshal(t)
		if err != nil {
			return nil, err
		}
		keep = append(keep, raw)
	}
	tasksJSON, err := json.Marshal(keep)
	if err != nil {
		return nil, err
	}
	f.rest["tasks"] = tasksJSON
	if _, ok := f.rest["version"]; !ok {
		f.rest["version"] = json.RawMessage(`"2.0.0"`)
	}
	var out bytes.Buffer
	enc := json.NewEncoder(&out)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(f.rest); err != nil {
		return nil, err
	}
	return out.Bytes(), nil
}

// WriteTasks merges tasks into <worktree>/.vscode/tasks.json and returns its path.
func WriteTasks(worktree string, tasks []VSTask) (string, error) {
	path := TasksPath(worktree)
	existing, err := os.ReadFile(path)
	if err != nil && !errors.Is(err, fs.ErrNotExist) {
		return "", err
	}
	data, err := MergeTasks(existing, tasks)
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return "", err
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o644); err != nil {
		return "", err
	}
	return path, os.Rename(tmp, path)
}
