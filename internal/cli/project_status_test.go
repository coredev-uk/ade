// onlyGitOnPath leaves git, and nothing else (so no nix), on PATH.
func onlyGitOnPath(t *testing.T) {
	t.Helper()
	git, err := exec.LookPath("git")
	if err != nil {
		t.Skip("git is not installed")
	}
	bin := t.TempDir()
	if err := os.Symlink(git, filepath.Join(bin, "git")); err != nil {
		t.Fatal(err)
	}
	t.Setenv("PATH", bin)
}

// projectWithSetup gives the codeEnv project a [project] table, its generated
// files, and returns the project directory.
func (e *codeEnv) projectWithSetup() string {
	e.t.Helper()
	manifest := "name = \"demo\"\n[project]\nagents = \"AGENTS.md\"\npackages = [\"go\", \"jq\"]\n" +
		"[repos.api]\npath = \"g/api\"\ndefault_branch = \"main\"\n[repos.web]\npath = \"g/web\"\ndefault_branch = \"main\"\n"
	snap := "source = \"x\"\nmanifest = '''\n" + manifest + "'''\n"
	dir := filepath.Join(e.root, "demo")
	if err := os.WriteFile(filepath.Join(dir, ".project.toml"), []byte(snap), 0o644); err != nil {
		e.t.Fatal(err)
	}
	write := func(path, content string, perm os.FileMode) {
		e.t.Helper()
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			e.t.Fatal(err)
		}
		if err := os.WriteFile(path, []byte(content), perm); err != nil {
			e.t.Fatal(err)
		}
	}
	write(filepath.Join(dir, "AGENTS.md"), "<!-- Generated by ADE from project.agents -->\n\nx\n", 0o644)
	write(devshell.ProjectShellPath(dir), devshell.ProjectScript("", []string{"go", "jq"}), 0o755)
	return dir
}

func (e *codeEnv) projectStatus(args ...string) string {
	e.t.Helper()
	cmd := newProjectCmd()
	var out bytes.Buffer
	cmd.SetOut(&out)
	cmd.SetErr(&out)
	cmd.SetArgs(append([]string{"status"}, args...))
	cmd.SilenceUsage, cmd.SilenceErrors = true, true
	if err := cmd.ExecuteContext(context.WithValue(context.Background(), ctxKey{}, e.app)); err != nil {
		e.t.Fatalf("ade project status: %v\n%s", err, out.String())
	}
	return out.String()
}

func TestProjectStatusShowsTheProjectWideSetup(t *testing.T) {
	e := newCodeEnv(t)
	dir := e.projectWithSetup()
	onlyGitOnPath(t) // no nix: the shell line says so

	out := e.projectStatus()
	for _, want := range []string{
		"demo  " + dir + "\n",
		"  agents    AGENTS.md -> AGENTS.md: written\n",
		"  shell     go jq: nix is not on PATH: panes, tasks and services run without these packages\n",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("text lacks %q:\n%s", want, out)
		}
	}

	jsonOut = true
	t.Cleanup(func() { jsonOut = false })
	var got []project.ProjectStatus
	if err := json.Unmarshal([]byte(e.projectStatus()), &got); err != nil || len(got) != 1 {
		t.Fatalf("json: %v", err)
	}
	su := got[0].Setup
	if su == nil || su.Agents == nil || !su.Agents.Written || su.Agents.Source != "AGENTS.md" {
		t.Fatalf("agents = %+v", su)
	}
	if su.Shell == nil || !su.Shell.Written || strings.Join(su.Shell.Packages, ",") != "go,jq" || su.Shell.Note == "" {
		t.Errorf("shell = %+v", su.Shell)
	}
}

// Without `[project]` keys the status has no setup lines and no "setup" in JSON.
func TestProjectStatusWithoutSetupHasNoSetupLines(t *testing.T) {
	e := newCodeEnv(t)
	out := e.projectStatus()
	for _, unwanted := range []string{"agents ", "shell "} {
		if strings.Contains(out, unwanted) {
			t.Errorf("unexpected %q:\n%s", unwanted, out)
		}
	}
	jsonOut = true
	t.Cleanup(func() { jsonOut = false })
	if out := e.projectStatus(); strings.Contains(out, `"setup"`) {
		t.Errorf("json has a setup object:\n%s", out)
	}
}

// --warm skips a project shell it cannot realise when nix is missing.
func TestWarmProjectShellsSkipsWithoutNix(t *testing.T) {
	e := newCodeEnv(t)
	dir := e.projectWithSetup()
	onlyGitOnPath(t)
	var say bytes.Buffer
	var res setupResult
	warmProjectShells(context.Background(), &say, e.app, &res)
	if len(res.Warm) != 1 || res.Warm[0].Status != "skipped" || res.Warm[0].Kind != "project" || res.Warm[0].Dir != dir {
		t.Fatalf("warm = %+v", res.Warm)
	}
	if !strings.Contains(say.String(), "skipped, nix is not on PATH") || len(res.Problems) != 0 {
		t.Errorf("say %q, problems %v", say.String(), res.Problems)
	}
}
